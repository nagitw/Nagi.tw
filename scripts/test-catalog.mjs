import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { catalogEntries, researchGroups, relatedEntries } from '../src/lib/catalog.ts';
import { projectLeadEditions } from '../src/lib/project-leads.ts';
const records = JSON.parse(readFileSync('src/data/migrated.json', 'utf8'));
const en = catalogEntries(records, 'en', ['project']);
assert.equal(en.filter(r => r.path === '/systems/medtrust/').length, 1, 'One card per project and language group');
assert.equal(en.find(r => r.path === '/systems/medtrust/').developmentStatus, undefined, 'Prototype is not a guessed development lifecycle');
assert.ok(!en.some(r => r.path.includes('infrastructure')), 'Compatibility page is not a second project');
assert.deepEqual(researchGroups([], 'en'), [], 'No empty or invented categories');
assert.ok(!researchGroups(records, 'en').some(g => ['ai-security', '5g-security'].includes(g.id)), 'No categories without published research');
const draft = { ...records.find(r => r.route === '/systems/medtrust/'), publicationStatus: 'draft' };
assert.equal(catalogEntries([draft], 'en', ['project']).length, 0);
const translated = records.find(r => r.route === '/zh/systems/medtrust/');
assert.equal(catalogEntries([draft, translated], 'en', ['project'])[0].record.locale, 'zh', 'Unapproved translation links to real original, never fabricated English');
const related = relatedEntries(records, '/systems/medtrust/', 'en');
assert.ok(related.some(r => r.record.kind === 'journal'));
assert.ok(related.some(r => r.record.kind === 'report'));
const withdrawn = records.map(r => r.kind === 'report' ? { ...r, publicationStatus: 'review' } : r);
assert.ok(!relatedEntries(withdrawn, '/systems/medtrust/', 'en').some(r => r.record.kind === 'report'), 'Related articles require separate approval');
const lead = { name: 'Fixture project', slug: 'fixture-project', evidence: false, developmentStatus: 'maintained', introduction: { en: 'Contributed to the project.' }, github: 'https://github.com/example/project' };
assert.deepEqual(projectLeadEditions([lead]), [], 'An introduction does not grant publication approval');
const publishedLead = projectLeadEditions([{ ...lead, publicationStatus: 'published' }]);
assert.equal(publishedLead.length, 1, 'Only real translations produce editions');
assert.equal(catalogEntries(publishedLead, 'en', ['project'])[0].developmentStatus, 'maintained');
assert.ok(!publishedLead[0].body.includes('Verified results'), 'Missing details do not produce empty sections');
console.log('Curated project/research metadata, nonempty categories and approved related articles: PASS');
const contribution = projectLeadEditions([{ ...lead, publicationStatus: 'published', role: { en: 'Contributor' }, contributions: { en: ['Reviewed parser behavior'] }, projectResults: { en: ['Upstream supports scanning'] } }])[0];
assert.equal(contribution.role, 'Contributor');
assert.deepEqual(contribution.contributions, ['Reviewed parser behavior']);
assert.deepEqual(contribution.projectResults, ['Upstream supports scanning']);
assert.deepEqual(contribution.verifiedResults, [], 'Upstream results are never personal verified results');
const researchEntries = researchGroups(records, 'en').flatMap(group => group.entries);
assert.ok(researchEntries.some(entry => entry.typeLabel === 'Research Project'));
assert.equal(researchEntries.find(entry => entry.path === '/labs/web-security/').typeLabel, 'Research Notes');
assert.ok(en.find(entry => entry.path === '/projects/autonomous-robot/').contributions.length > 0);
